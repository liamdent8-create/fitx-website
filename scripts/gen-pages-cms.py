"""Regenerate .pages.yml (Pages CMS) from the shape of the content files,
so the editor never drops fields. Run after adding or renaming content keys:
    python3 scripts/gen-pages-cms.py
"""
import json, re

FILES = [
    ('studio', 'Studio page text', 'content/studio.json'),
    ('timetable', 'Timetable page text', 'content/timetable.json'),
    ('faq', 'Studio FAQs', 'content/studio-faq.json'),
    ('videos', 'Videos', 'content/videos.json'),
    ('site', 'Contact details and links', 'content/site.json'),
]


def label(key):
    return re.sub(r'(?<!^)([A-Z])', r' \1', key).replace('_', ' ').capitalize()


def field(key, value, indent):
    pad = ' ' * indent
    out = []
    if isinstance(value, bool):
        out.append(f'{pad}- {{ name: {key}, label: "{label(key)}", type: boolean }}')
    elif isinstance(value, (int, float)):
        out.append(f'{pad}- {{ name: {key}, label: "{label(key)}", type: number }}')
    elif isinstance(value, str):
        kind = 'text' if len(value) > 80 else 'string'
        out.append(f'{pad}- {{ name: {key}, label: "{label(key)}", type: {kind} }}')
    elif isinstance(value, list) and value and isinstance(value[0], str):
        out.append(f'{pad}- {{ name: {key}, label: "{label(key)}", type: string, list: true }}')
    elif isinstance(value, list) and value and isinstance(value[0], dict):
        out.append(f'{pad}- name: {key}\n{pad}  label: "{label(key)}"\n{pad}  type: object\n{pad}  list: true\n{pad}  fields:')
        keys = {}
        for item in value:
            keys.update(item)
        for k, v in keys.items():
            out += field(k, v, indent + 4)
    elif isinstance(value, dict):
        out.append(f'{pad}- name: {key}\n{pad}  label: "{label(key)}"\n{pad}  type: object\n{pad}  fields:')
        for k, v in value.items():
            out += field(k, v, indent + 4)
    return out


lines = [
    '# Pages CMS (https://pagescms.org): a free editor for this repo.',
    '# Sign in with GitHub, pick this repo, and edit the fields in a form.',
    '# Saving commits to GitHub; Netlify rebuilds the site automatically.',
    '# Generated by scripts/gen-pages-cms.py. Do not edit by hand.',
    'content:',
]
for name, title, path in FILES:
    data = json.load(open(path))
    lines += [f'  - name: {name}', f'    label: "{title}"', '    type: file', f'    path: {path}', '    format: json', '    fields:']
    for k, v in data.items():
        if not k.startswith('_'):
            lines += field(k, v, 6)
open('.pages.yml', 'w').write('\n'.join(lines) + '\n')
print('wrote .pages.yml')
